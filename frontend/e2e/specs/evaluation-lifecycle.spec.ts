import { test, expect } from '../fixtures/test';
import { login, signOut, submitEvaluation } from '../helpers/workflows';

test('S02 create a questionnaire, activate it and generate unique assignments @core', async ({ page, fixture, evidence }) => {
  await login(page, fixture, 'admin');
  await page.goto('/admin/forms');
  expect((await evidence('before-create')).forms).toHaveLength(0);
  await page.getByRole('button', { name: 'Create Form', exact: true }).click();
  await page.getByPlaceholder('e.g., Mid-Year Peer Evaluation').fill(fixture.title);
  await page.getByRole('dialog').getByRole('button', { name: 'Create Form', exact: true }).click();
  await page.getByText('Rating Scale', { exact: true }).click();
  await page.getByPlaceholder('Type your question here...').fill('Communication');
  await page.getByRole('button', { name: 'Save Draft', exact: true }).click();
  await expect(page.getByText('Draft Saved', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Activate Form', exact: true }).click();
  await page.getByRole('button', { name: 'Yes, Activate', exact: true }).click();
  await page.getByRole('tab', { name: /^Assignments/ }).click();
  await page.getByRole('button', { name: 'Add Rule', exact: true }).click();
  const generation = page.waitForResponse(response => response.url().endsWith('/api/assignment-rules/generate/') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Generate Assignments', exact: true }).click();
  expect((await generation).ok()).toBe(true);
  await expect(page.getByRole('button', { name: 'Generate Assignments', exact: true })).toBeEnabled();
  const first = await evidence('generated', { formCount: 1, questions: 1, pairs: 6 });
  expect(first.forms).toHaveLength(1);
  expect(first.questions).toHaveLength(1);
  expect(first.forms[0].is_active).toBe(true);
  expect(first.assignments).toHaveLength(6);
  expect(new Set(first.assignments.map(row => row.evaluator_id_id + ':' + row.evaluatee_id_id)).size).toBe(6);
  expect(first.assignments.every(row => row.evaluator_id_id !== row.evaluatee_id_id)).toBe(true);
  const regeneration = page.waitForResponse(response => response.url().endsWith('/api/assignment-rules/generate/') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Generate Assignments', exact: true }).click();
  expect((await regeneration).ok()).toBe(true);
  await expect(page.getByRole('button', { name: 'Generate Assignments', exact: true })).toBeEnabled();
  expect((await evidence('regenerated', { pairCountUnchanged: 6 })).assignments).toEqual(first.assignments);
});

test('S03 save and resume a draft, then commit the correct weighted score @core', async ({ page, fixture, evidence }) => {
  await login(page, fixture);
  expect((await evidence('before-answer')).responses).toHaveLength(0);
  await submitEvaluation(page, fixture, true);
  const draft = await evidence('draft', { status: 'In Progress', responses: 2 });
  expect(draft.responses).toHaveLength(2);
  expect(draft.assignments[0].status).toBe('In Progress');
  expect(draft.assignments[0].total_score).toBeNull();
  await page.reload();
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await expect(page.locator('#q' + fixture.questionIds[0] + '-2')).toHaveAttribute('aria-checked', 'true');
  await expect(page.locator('#q' + fixture.questionIds[1] + '-4')).toHaveAttribute('aria-checked', 'true');
  await page.getByRole('button', { name: 'Submit', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm Submit', exact: true }).click();
  await expect(page).toHaveURL(/\/member\/evaluations$/);
  const expected = (2 * 1 + 4 * 3) / 4;
  const final = await evidence('completed', { status: 'Completed', responses: 2, totalScore: expected });
  expect(final.assignments[0].status).toBe('Completed');
  expect(final.assignments[0].total_score).toBeCloseTo(expected, 8);
  expect(final.assignments[0].submitted_at).toBeTruthy();
  expect(final.responses).toHaveLength(2);
  await page.goto('/member/evaluations/' + fixture.assignmentId);
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await expect(page.locator('#q' + fixture.questionIds[0] + '-2')).toBeDisabled();
});

test('S04 release a submitted evaluation and show the member aggregate @core', async ({ page, fixture, evidence }) => {
  await login(page, fixture);
  await submitEvaluation(page, fixture);
  await signOut(page);
  await login(page, fixture, 'peer');
  await page.goto('/member/results');
  await expect(page.getByText('3.5', { exact: true })).toHaveCount(0);
  await evidence('before-release', { resultsReleased: false });
  await signOut(page);
  await login(page, fixture, 'admin');
  await page.goto('/admin/forms');
  await page.locator('[title="Double-click to open in Form Editor"]').filter({ hasText: fixture.title }).getByRole('button').click();
  await page.getByRole('menuitem', { name: 'Release Results', exact: true }).click();
  await page.getByRole('button', { name: 'Yes, Release Results', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const data = await evidence('released', { resultsReleased: true, active: false, totalScore: 3.5 });
  expect(data.forms[0].results_released).toBe(true);
  expect(data.forms[0].is_active).toBe(false);
  expect(data.assignments[0].total_score).toBeCloseTo(3.5, 8);
  expect(data.audit.length).toBeGreaterThan(0);
  await signOut(page);
  await login(page, fixture, 'peer');
  await page.goto('/member/results');
  await expect(page.getByText('3.5', { exact: true })).toBeVisible();
  await evidence('member-result', { displayedScore: 3.5 });
});
